class CryptoAlphaSystem:
    """
    Main CryptoAlpha system controller.

    Manages:
    - Continuous analysis pipeline
    - Telegram bot
    - Performance tracking
    - Memory systems
    """

    def __init__(
        self,
        exchange: str = "binance",
        chains: Optional[List[str]] = None,
        interval_minutes: int = 15,
        enable_telegram: bool = True,
    ):
        """
        Initialize the CryptoAlpha system.

        Args:
            exchange: Exchange for price data
            chains: Chains for on-chain data
            interval_minutes: Minutes between analysis runs
            enable_telegram: Whether to enable Telegram bot
        """
        self.exchange = exchange
        self.chains = chains or ["ethereum"]
        self.interval_minutes = interval_minutes
        self.enable_telegram = enable_telegram

        # Load config
        self.config = load_config()

        # Initialize components
        self.database = SignalDatabase()
        self.vector_store = VectorStore()
        self.episodic_memory = EpisodicMemory(vector_store=self.vector_store)
        self.performance_tracker = PerformanceTracker(signal_db=self.database)
        self.working_memory = get_working_memory()

        # Analysis pipeline
        self.pipeline: Optional[AnalysisPipeline] = None

        # Telegram bot
        self.bot: Optional[CryptoAlphaBot] = None

        # Control
        self._running = False
        self._shutdown_event = asyncio.Event()

        logger.info(
            "CryptoAlpha system initialized",
            exchange=exchange,
            chains=chains,
            interval_minutes=interval_minutes,
        )

    def _on_new_signal(self, result) -> None:
        """Callback for new signals from pipeline."""
        if result.signal and result.approved:
            symbol = result.symbol
            signal = result.signal

            # Update working memory
            self.working_memory.add_signal(signal, approved=True)
            self.working_memory.set_cooldown(symbol)

            # Log the signal
            logger.info(
                f"New signal: {signal.signal_type.value.upper()} {symbol}",
                confidence=f"{signal.confidence:.0%}",
                entry=f"${signal.entry_price:,.2f}",
            )

            # Send Telegram alert (async)
            if self.bot and self.bot.alert_manager:
                asyncio.create_task(
                    self.bot.alert_manager.send_result_alert(result)
                )

    async def _on_trade_signal(self, signal) -> None:
        """Send Telegram notification for trade signals."""
        if not self.bot or not signal:
            return
        
        try:
            emoji = "🟢" if signal.signal == 'BUY' else "🔴" if signal.signal == 'SELL' else "⚪"
            msg = f"""{emoji} *{signal.signal} SIGNAL: {signal.symbol}*

Confidence: {signal.confidence:.0f}%
Entry: ${signal.entry_price:,.4f}

_Generated by CryptoAlpha ML_
"""
            for sub in self.bot.alert_manager.subscriptions.values():
                if sub.enabled:
                    try:
                        await self.bot.alert_manager.bot.send_message(
                            chat_id=sub.chat_id,
                            text=msg,
                            parse_mode='Markdown'
                        )
                    except Exception as e:
                        pass
        except Exception as e:
            pass

    def start_pipeline(
        self,
        tokens: Optional[List[dict]] = None,
    ) -> None:
        """Start the lite analysis pipeline (no LLM).
        
        Uses ML ensemble only - no Gemini API calls.
        """
        # DISABLED: Batched pipeline (uses Gemini API)
        # self.pipeline = get_batched_pipeline()
        # self.pipeline.on_signal = lambda sig: asyncio.create_task(self._on_trade_signal(sig))
        # self.pipeline.start()
        self.pipeline = None  # No LLM pipeline
        
        # Use lite pipeline only (ML ensemble, no Gemini)
        self.lite_pipeline = get_lite_pipeline()
        self.lite_pipeline.start()

        logger.info(
            "Lite Pipeline started (LLM disabled)",
            interval_minutes=self.interval_minutes,
        )

    def stop_pipeline(self) -> None:
        """Stop the analysis pipeline."""
        if self.pipeline:
            self.pipeline.stop()
            logger.info("Pipeline stopped")

    async def run_async(self) -> None:
        """Run the system asynchronously."""
        self._running = True

        try:
            # Start Telegram bot if enabled
            if self.enable_telegram:
                bot_token = self.config.telegram.bot_token
                if not bot_token:
                    logger.warning("Telegram bot token not configured, running without bot")
                else:
                    self.bot = create_bot(
                        bot_token=bot_token,
                        exchange=self.exchange,
                        chains=self.chains,
                    )
                    await self.bot.run_async()
                    logger.info("Telegram bot started")

            # Start pipeline
            self.start_pipeline()

            # Main loop
            logger.info("CryptoAlpha system running. Press Ctrl+C to stop.")

            # Performance tracking interval (every hour)
            last_performance_check = datetime.now()

            while self._running:
                try:
                    # Check for shutdown
                    await asyncio.wait_for(
                        self._shutdown_event.wait(),
                        timeout=60,  # Check every minute
                    )
                    break
                except asyncio.TimeoutError:
                    pass

                # Periodic tasks
                now = datetime.now()

                # Hourly performance update
                if (now - last_performance_check).total_seconds() >= 3600:
                    self._update_performance()
                    last_performance_check = now

                # Clean stale data
                self.working_memory.cleanup_stale_data(max_age_hours=24)

        except Exception as e:
            logger.exception(f"System error: {e}")
        finally:
            await self.shutdown()

    def _update_performance(self) -> None:
        """Update performance metrics."""
        try:
            self.performance_tracker.save_daily_metrics()
            self.performance_tracker.update_confidence_calibration()

            metrics = self.performance_tracker.calculate_metrics(days=7)
            logger.info(
                "Performance update",
                win_rate=f"{metrics.win_rate:.1%}",
                sharpe=f"{metrics.sharpe_ratio:.2f}",
                total_pnl=f"{metrics.total_pnl:.1f}%",
            )
        except Exception as e:
            logger.error(f"Performance update failed: {e}")

    async def shutdown(self) -> None:
        """Shutdown the system gracefully."""
        logger.info("Shutting down CryptoAlpha system...")
        self._running = False

        # Stop pipeline
        self.stop_pipeline()

        # Stop Telegram bot
        if self.bot:
            try:
                await self.bot.stop_async()
            except Exception as e:
                logger.error(f"Error stopping bot: {e}")

        # Close database
        self.database.close()

        # Final performance save
        try:
            self.performance_tracker.save_daily_metrics()
        except Exception:
            pass

        logger.info("CryptoAlpha system stopped")

    def run(self) -> None:
        """Run the system (blocking)."""
        # Set up signal handlers
        def handle_signal(sig, frame):
            logger.info(f"Received signal {sig}, initiating shutdown...")
            self._shutdown_event.set()

        signal.signal(signal.SIGINT, handle_signal)
        signal.signal(signal.SIGTERM, handle_signal)

        # Run async loop
        asyncio.run(self.run_async())


def run_quick_analysis(
    symbol: str,
    exchange: str = "binance",
    timeframe: str = "1h",
) -> None:
    """Run a quick analysis for a single symbol."""
    logger.info(f"Quick analysis: {symbol}")

    analyzer = QuickAnalyzer(exchange=exchange)
    result = analyzer.analyze(symbol=symbol, timeframe=timeframe)

    print("\n" + "=" * 50)
    print(f"ANALYSIS: {symbol}")
    print("=" * 50)

    if result.signal:
        signal = result.signal
        print(f"\nSignal: {signal.signal_type.value.upper()}")
        print(f"Strength: {signal.strength.value}")
        print(f"Confidence: {signal.confidence:.0%}")
        print(f"\nEntry: ${signal.entry_price:,.2f}")
        print(f"Stop Loss: ${signal.stop_loss:,.2f}")
        print(f"Take Profit: ${signal.take_profit:,.2f}")
        print(f"Position Size: {signal.position_size_pct:.1f}%")
        print(f"\nApproved: {'Yes' if result.approved else 'No'}")
    else:
        print("\nNo signal generated")

    print(f"\nRegime: {result.regime}")
    print(f"Analysis Time: {result.analysis_time:.1f}s")

    if result.errors:
        print(f"\nErrors: {', '.join(result.errors)}")

    print("=" * 50)


def run_performance_report(days: int = 30) -> None:
    """Generate and display performance report."""
    tracker = PerformanceTracker()
    report = tracker.generate_report(days=days)
    print(report)


def main():
    """Main entry point."""
    parser = argparse.ArgumentParser(
        description="CryptoAlpha Trading Signal System"
    )

    subparsers = parser.add_subparsers(dest="command", help="Commands")

    # Run command (default)
    run_parser = subparsers.add_parser("run", help="Run the full system")
    run_parser.add_argument(
        "--exchange", default="binance", help="Exchange for price data"
    )
    run_parser.add_argument(
        "--chains", nargs="+", default=["ethereum"], help="Chains for on-chain data"
    )
    run_parser.add_argument(
        "--interval", type=int, default=None, help="Analysis interval in minutes (default: from config)"
    )
    run_parser.add_argument(
        "--no-telegram", action="store_true", help="Disable Telegram bot"
    )

    # Analyze command
    analyze_parser = subparsers.add_parser("analyze", help="Quick single analysis")
    analyze_parser.add_argument("symbol", help="Symbol to analyze (e.g., BTC/USDT)")
    analyze_parser.add_argument(
        "--exchange", default="binance", help="Exchange for price data"
    )
    analyze_parser.add_argument(
        "--timeframe", default="1h", help="Chart timeframe"
    )

    # Performance command
    perf_parser = subparsers.add_parser("performance", help="Show performance report")
    perf_parser.add_argument(
        "--days", type=int, default=30, help="Days to analyze"
    )

    # Bot command
    bot_parser = subparsers.add_parser("bot", help="Run Telegram bot only")
    bot_parser.add_argument(
        "--exchange", default="binance", help="Exchange for price data"
    )

    args = parser.parse_args()

    # Show banner
    print("\n" + "=" * 50)
    print("  CryptoAlpha Trading Signal System")
    print("  Hybrid Neuro-Symbolic Analysis Platform")
    print("=" * 50 + "\n")

    if args.command == "analyze":
        run_quick_analysis(
            symbol=args.symbol,
            exchange=args.exchange,
            timeframe=args.timeframe,
        )

    elif args.command == "performance":
        run_performance_report(days=args.days)

    elif args.command == "bot":
        config = load_config()
        if not config.telegram.bot_token:
            print("Error: TELEGRAM_BOT_TOKEN not configured")
            sys.exit(1)

        bot = create_bot(
            bot_token=config.telegram.bot_token,
            exchange=args.exchange,
        )
        print("Starting Telegram bot...")
        bot.run()

    else:
        # Default: run full system
        config = load_config()
        system = CryptoAlphaSystem(
            exchange=getattr(args, "exchange", "binance"),
            chains=getattr(args, "chains", ["ethereum"]),
            interval_minutes=getattr(args, "interval", None) or config.analysis.analysis_interval_minutes,
            enable_telegram=not getattr(args, "no_telegram", False),
        )
        system.run()


if __name__ == "__main__":
    main()
